import { flush, setup } from './helpers/lunar-controller'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { attachLunarController, LUNAR_BUDGET, lunarPixelRatio, LunarGpuMemoryError, LunarTextureLimitError, type LunarState } from '../src/lunar-controller'
import type { LunarPose, LunarResolution, LunarScene } from '../src/lunar-scene'
import { defaultLunarView, LUNAR_ZOOM, type LunarView } from '../src/lunar-view'

describe('lunar pointer and keyboard interaction', () => {
	it('normalizes drag against the actual host while loading without ResizeObserver support', async () => {
		const h = setup({ reducedMotion: true, deferred: true, observers: false })
		h.pointer('pointerdown')
		h.pointer('pointermove', { clientX: 30, clientY: 10 })
		expect(h.state?.phase).toBe('loading')
		h.resolve()
		await flush()
		h.clock.advance(100)
		expect(h.rendered.at(-1)!.pose.yaw).toBeCloseTo((30 / h.host.clientWidth) * Math.PI * 1.6)
		expect(h.rendered.at(-1)!.pose.pitch).toBeCloseTo((10 / h.host.clientHeight) * Math.PI)
		expect(h.clock.tasks.size).toBe(0)
	})

	it('mouse drag rotates both axes, clamps pitch, and suppresses the following click', async () => {
		const h = setup({ reducedMotion: true })
		await h.ready()
		h.pointer('pointerdown')
		await flush()
		h.pointer('pointermove', { clientX: 40, clientY: 1000 })
		h.clock.advance(100)
		expect(h.state?.dragging).toBe(true)
		expect(h.surface.hasPointerCapture(1)).toBe(true)
		expect(h.rendered.at(-1)?.pose).toMatchObject({ pitch: 0.65 })
		const yaw = h.rendered.at(-1)!.pose.yaw
		h.pointer('pointerup', { clientX: 40, clientY: 1000 })
		h.click()
		h.clock.advance(100)
		expect(h.rendered.at(-1)!.pose.yaw).toBe(yaw)
		expect(h.state?.dragging).toBe(false)
		expect(h.surface.captured.size).toBe(0)
		h.click()
		h.clock.advance(100)
		expect(h.rendered.at(-1)!.pose.yaw).toBeCloseTo(yaw + Math.PI / 8)
	})

	it('live single-touch drag rotates both axes and captures only after movement', async () => {
		const h = setup({ reducedMotion: true })
		await h.ready()
		h.pointer('pointerdown', { pointerType: 'touch' })
		expect(h.surface.setPointerCapture).not.toHaveBeenCalled()
		await flush()
		h.pointer('pointermove', { pointerType: 'touch', clientX: 40, clientY: 8 })
		h.clock.advance(100)
		expect(h.surface.setPointerCapture).toHaveBeenCalledWith(1)
		expect(h.rendered.at(-1)!.pose.yaw).toBeGreaterThan(0)
		expect(h.rendered.at(-1)!.pose.pitch).toBeCloseTo(8 / h.host.clientHeight * Math.PI)
	})

	it('vertical live touch rotates pitch and suppresses its synthetic click', async () => {
		const h = setup({ reducedMotion: true })
		await h.ready()
		h.pointer('pointerdown', { pointerType: 'touch' })
		await flush()
		const move = h.pointer('pointermove', { pointerType: 'touch', clientX: 2, clientY: 30 })
		h.pointer('pointerup', { pointerType: 'touch', clientX: 2, clientY: 30 })
		h.click()
		h.clock.advance(100)
		expect(move.defaultPrevented).toBe(true)
		expect(h.surface.setPointerCapture).toHaveBeenCalledWith(1)
		expect(h.rendered.at(-1)!.pose.pitch).toBeCloseTo(30 / h.host.clientHeight * Math.PI)
		expect(h.rendered.at(-1)!.pose.yaw).toBeCloseTo(2 / h.host.clientWidth * Math.PI * 1.6)
		expect(h.clock.tasks.size).toBe(0)
	})

	it('ignores nonprimary/right button and unrelated pointer events', async () => {
		const h = setup({ reducedMotion: true })
		await h.ready()
		h.pointer('pointerdown', { isPrimary: false })
		h.pointer('pointerdown', { button: 2 })
		expect(h.factory).not.toHaveBeenCalled()
		h.pointer('pointerdown')
		await flush()
		h.pointer('pointermove', { pointerId: 2, clientX: 100 })
		h.pointer('pointerup', { pointerId: 2 })
		h.clock.advance(100)
		expect(h.rendered.at(-1)!.pose.yaw).toBe(0)
		expect(h.surface.hasPointerCapture(1)).toBe(true)
	})

	it.each(['pointercancel', 'lostpointercapture'])('%s releases drag and suppresses any following click', async cancellation => {
		const h = setup({ reducedMotion: true })
		await h.ready()
		h.pointer('pointerdown')
		await flush()
		h.pointer('pointermove', { clientX: 30 })
		h.clock.advance(100)
		const yaw = h.rendered.at(-1)!.pose.yaw
		h.pointer(cancellation)
		h.click()
		h.clock.advance(100)
		expect(h.state?.dragging).toBe(false)
		expect(h.surface.captured.size).toBe(0)
		expect(h.rendered.at(-1)!.pose.yaw).toBe(yaw)
		expect(h.clock.tasks.size).toBe(0)
	})

	it('ignores tiny pointer jitter and permits the normal click', async () => {
		const h = setup({ reducedMotion: true })
		await h.ready()
		h.pointer('pointerdown')
		await flush()
		h.pointer('pointermove', { clientX: 2, clientY: 2 })
		h.pointer('pointerup')
		h.click()
		h.clock.advance(100)
		expect(h.rendered.at(-1)!.pose.yaw).toBeCloseTo(Math.PI / 8)
	})

	it('arrows move the accessible native control, Home resets and pauses, unrelated keys are untouched', async () => {
		const h = setup({ reducedMotion: true })
		await h.ready()
		expect(h.key('Tab').defaultPrevented).toBe(false)
		expect(h.factory).not.toHaveBeenCalled()
		expect(h.key('ArrowRight').defaultPrevented).toBe(true)
		h.key('ArrowUp')
		await flush()
		h.clock.advance(100)
		expect(h.rendered.at(-1)!.pose).toMatchObject({ yaw: 0.15, pitch: -0.1 })
		h.key('ArrowLeft')
		h.key('ArrowDown')
		h.controller.toggleRotation()
		h.clock.advance(100)
		expect(h.key('Home').defaultPrevented).toBe(true)
		h.clock.advance(100)
		expect(h.rendered.at(-1)!.pose).toEqual({ yaw: 0, pitch: 0, orbit: 0, stationOrbit: 0 })
		expect(h.state?.rotating).toBe(false)
		expect(h.clock.tasks.size).toBe(0)
	})
})

